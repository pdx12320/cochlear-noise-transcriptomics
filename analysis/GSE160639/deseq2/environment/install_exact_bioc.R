#!/usr/bin/env Rscript
# Authorized isolated installation; never updates an existing/shared library.
root <- normalizePath(commandArgs(trailingOnly=TRUE)[[1]],mustWork=TRUE)
stopifnot(as.character(getRversion())=="4.6.1")
lib <- file.path(root,"R_library")
downloads <- file.path(root,"package_sources")
dir.create(lib,showWarnings=FALSE)
dir.create(downloads,showWarnings=FALSE)
.libPaths(c(lib,.Library),include.site=FALSE)
options(repos=c(CRAN="https://cloud.r-project.org"),timeout=300,Ncpus=4)
# Four package jobs, each with a single compile job: at most four build threads.
Sys.setenv(MAKEFLAGS="-j1",OMP_NUM_THREADS="1",OPENBLAS_NUM_THREADS="1",MKL_NUM_THREADS="1")
utils::install.packages("BiocManager",lib=lib,type="source",destdir=downloads,Ncpus=4)
stopifnot(requireNamespace("BiocManager",quietly=TRUE))
repos <- BiocManager::repositories(version="3.23")
writeLines(paste(names(repos),repos,sep="\t"),file.path(root,"INSTALL_REPOSITORIES.tsv"))
avail <- utils::available.packages(repos=repos,type="source")
stopifnot("DESeq2" %in% rownames(avail),avail["DESeq2","Version"]=="1.52.0")
utils::write.table(avail["DESeq2",,drop=FALSE],file.path(root,"TARGET_DESEQ2_REPOSITORY_RECORD.tsv"),sep="\t",quote=FALSE,row.names=FALSE,na="NA")
BiocManager::install("DESeq2",version="3.23",lib=lib,ask=FALSE,update=FALSE,
  type="source",dependencies=c("Depends","Imports","LinkingTo"),Ncpus=4,destdir=downloads)
stopifnot(requireNamespace("DESeq2",quietly=TRUE),as.character(utils::packageVersion("DESeq2"))=="1.52.0")
library(DESeq2)
ip <- utils::installed.packages(lib.loc=.libPaths())
utils::write.table(ip,file.path(root,"INSTALLED_R_PACKAGES.tsv"),sep="\t",quote=FALSE,row.names=FALSE,na="NA")
capture.output(sessionInfo(),file=file.path(root,"INSTALL_SESSIONINFO.txt"))
sources <- list.files(downloads,full.names=TRUE,recursive=FALSE)
hashes <- vapply(sources,function(p) {
  z<-system2(Sys.which("sha256sum"),shQuote(p),stdout=TRUE)
  if(!is.null(attr(z,"status"))) stop("Hash failure")
  sub(" .*","",z[[1]])
},character(1))
utils::write.table(data.frame(file=basename(sources),sha256=unname(hashes)),file.path(root,"PACKAGE_SOURCE_SHA256.tsv"),sep="\t",quote=FALSE,row.names=FALSE)
writeLines("EXACT_RUNTIME_READY_R4.6.1_DESEQ2_1.52.0",file.path(root,"RUNTIME_STATUS.txt"))
message("EXACT_RUNTIME_READY_R4.6.1_DESEQ2_1.52.0")
